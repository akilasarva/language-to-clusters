"""Per-environment semantic-mode <-> HDBSCAN-cluster-id taxonomy.

A taxonomy is a YAML file with the schema::

    environment: <str>
    source: <path to cluster_id_to_label_*.json that seeded it>
    modes:
      "Road: On":                      [5, 6, 8, 9, 10, 11, 12]
      "Intersection: Approach/Enter":  [7]
      "Intersection: In":              [0, 1, 2]
      "Open Space":                    [3, 4]
      ...

Multiple semantic modes may map to overlapping cluster id sets — the executor
treats *any* listed id as "in this mode" when watching ``/predicted_cluster``,
and uses the **first** id as the canonical scalar ``start_cluster`` /
``goal_cluster`` in the brain-shaped linear plan.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Iterable, Mapping

import yaml


class TaxonomyError(ValueError):
    """Raised for malformed taxonomy files or unknown-mode lookups."""


@dataclass(frozen=True)
class ClusterTaxonomy:
    """In-memory view of a ``cluster_map.<env>.yaml`` file."""

    environment: str
    source: str | None
    modes: Mapping[str, tuple[int, ...]]
    # Per-mode execution metadata, generated by
    # bev_pipeline.taxonomy_export.build_hierarchical_cluster_map. Optional: files
    # written before it existed simply have none, and the defaults below preserve
    # the previous behaviour exactly.
    #   accept_degraded:   coarser cluster ids that may satisfy this mode on a
    #                      LANDMARK-triggered step, where a Detect(...) predicate
    #                      carries the real evidence and the cluster is only a
    #                      permissive guard. Never applied to traverse steps.
    #   perception_backed: False when the mode is a plan-level construct in this
    #                      environment rather than something a classifier can
    #                      emit (e.g. "Intersection: In" on the real campus).
    mode_meta: Mapping[str, Mapping[str, object]] = None  # type: ignore[assignment]
    # Optional CARLA-specific spatial data.
    centroids: Mapping[str, tuple[float, float, float]] = None  # type: ignore[assignment]
    bearing_map: Mapping[str, float] = None  # type: ignore[assignment]

    # ------------------------------------------------------------------ #
    # Lookup                                                              #
    # ------------------------------------------------------------------ #
    #: mode -> axis name. Empty for single-axis maps, where every mode is an
    #: alternative to every other and union is the right merge.
    axes: dict = field(default_factory=dict)

    def __contains__(self, mode: str) -> bool:
        return self.canonical_mode(mode) is not None

    def canonical_mode(self, mode: str) -> str | None:
        r"""This taxonomy's own spelling of ``mode``, or None if it has none.

        ONE collapse rule, applied in one place. Mode names reach us in several
        spellings — the STL compiler lowercases a macro (``\Phi_{Path}`` ->
        ``path``) while the campus maps spell it ``Path``, ``Space: Open``,
        ``Road: On``. Every comparison must use the same rule: if the formula gate
        collapsed case while ``resolve`` matched exactly, ``G \Phi_{Path}`` against
        a ``Path`` taxonomy would pass validation and then raise ``TaxonomyError``
        during materialization — the crash-instead-of-retry failure
        ``validate_plan_modes`` exists to prevent.

        Collapsing ignores only case and separators, so it cannot mask a real
        typo: ``pth`` still fails.
        """
        if mode is None:
            return None
        if mode in self.modes:
            return mode
        want = _collapse_mode(mode)
        for known in self.modes:
            if _collapse_mode(known) == want:
                return known

        # Concept fallback, for names that drifted by RENAME rather than spelling:
        # `Open Space` -> `Space: Open`, `Road: On` -> `On: Path`. See mode_concepts.
        #
        # When several modes here share a concept -- `full_campus_1hz` has Approach:,
        # In: and Exit: Junction -- the tie is broken by the order they are listed in
        # CONCEPTS, core spelling first. Deterministic rather than dict order, and it
        # means `junction` resolves to `In: Junction` there instead of failing. A map
        # with two genuinely different modes under one concept would still resolve to
        # the higher-ranked one, which is why that ordering is a deliberate list and
        # not alphabetical.
        from .mode_concepts import RANK, concept_of
        want_concept = concept_of(mode)
        if want_concept is None:
            return None
        hits = [k for k in self.modes if concept_of(k) == want_concept]
        if not hits:
            return None
        return min(hits, key=lambda k: (RANK.get(k, 99), k))

    def resolve(self, mode: str) -> tuple[int, ...]:
        """Return the cluster id tuple for ``mode``.

        Raises ``TaxonomyError`` if the mode is not in the YAML.
        """
        canon = self.canonical_mode(mode)
        if canon is None:
            raise TaxonomyError(
                f"semantic mode {mode!r} not in taxonomy for environment "
                f"{self.environment!r}; legal modes: {sorted(self.modes)}"
            )
        return self.modes[canon]

    def canonical_id(self, mode: str) -> int:
        """First cluster id listed for ``mode`` — used as the scalar id brain sees."""
        ids = self.resolve(mode)
        if not ids:
            raise TaxonomyError(
                f"semantic mode {mode!r} maps to an empty cluster id list"
            )
        return ids[0]

    def accept_clusters(self, mode: str, *, degraded: bool = False) -> tuple[int, ...]:
        """Cluster ids that count as "in ``mode``", preferred-first.

        ``degraded=False`` (default) returns exactly ``resolve(mode)`` — the
        mode's own id plus anything that reaches it by subsumption. This is what
        a ``traverse`` step uses, where the cluster IS the evidence.

        ``degraded=True`` additionally appends ``mode_meta[mode].accept_degraded``
        — the coarser ids that may satisfy the step when the fine classifier does
        not fire. Only valid for ``landmark``-triggered steps; the caller is
        responsible for that gate, not this method.
        """
        ids = list(self.resolve(mode))
        if not degraded:
            return tuple(ids)
        for cid in self._meta_for(mode).get("accept_degraded", ()) or ():
            if cid not in ids:
                ids.append(int(cid))
        return tuple(ids)

    def is_perception_backed(self, mode: str) -> bool:
        """False when ``mode`` is a plan-level construct in this environment.

        Defaults to True so taxonomies written before ``mode_meta`` existed keep
        behaving as they did.
        """
        self.resolve(mode)          # raises TaxonomyError on unknown mode
        return bool(self._meta_for(mode).get("perception_backed", True))

    def _meta_for(self, mode: str) -> Mapping[str, object]:
        if not self.mode_meta:
            return {}
        return self.mode_meta.get(mode) or {}

    def modes_for_prompt(self) -> list[str]:
        """Sorted list of legal mode strings, ready to splice into the user message.

        Returned VERBATIM and unannotated: the prompt tells the generator to copy these into
        `start_mode`/`goal_mode` exactly, so decorating them here would make it emit
        "asphalt [surface]" as a mode name and fail validation. The axis goes in
        `axes_note()` instead, as a separate line.
        """
        return sorted(self.modes.keys())

    def axes_note(self) -> str:
        """One line telling the generator which AXIS each mode measures, or "" if none.

        The axis has to reach the generator or the distinction cannot be used. E.g. on
        `carla_town05_sidewalks` (axes: path/junction = topology, sidewalk/asphalt =
        surface), given only the bare names the generator can render "staying off the
        sidewalk" as `forbid_modes: ['path']` -- the TOPOLOGY axis. The comment at the
        `axes` parse site explains why the distinction matters.

        Empty when a taxonomy declares no axes, so environments without axes are
        unaffected.
        """
        if not self.axes:
            return ""
        by = {}
        for m, ax in sorted(self.axes.items()):
            by.setdefault(ax, []).append(m)
        parts = "; ".join(f"{ax}: {', '.join(ms)}" for ax, ms in sorted(by.items()))
        return ("Mode AXES -- " + parts + ". Modes on the SAME axis are alternatives; modes "
                "on DIFFERENT axes are simultaneous facts about one place. A constraint "
                "about the SURFACE underfoot (\"stay off the sidewalk\", \"keep to the "
                "asphalt\") belongs on the surface axis, NOT on the topology axis -- "
                "topologically a sidewalk IS a path, so forbidding `path` does not say it.")

    def label_for_id(self, cluster_id: int) -> str | None:
        """Inverse lookup: return any mode that contains ``cluster_id`` (or None)."""
        for mode, ids in self.modes.items():
            if cluster_id in ids:
                return mode
        return None

    def centroid_map(self) -> dict[str, list[float]]:
        """Return ``{cluster_id_str: [x, y, z]}`` or empty dict if not defined."""
        if not self.centroids:
            return {}
        return {k: list(v) for k, v in self.centroids.items()}

    def bearing_map_dict(self) -> dict[str, float]:
        """Return ``{"start_id-goal_id": degrees_relative}`` or empty dict."""
        if not self.bearing_map:
            return {}
        return dict(self.bearing_map)

    def cluster_labels(self) -> dict[int, str]:
        """``{cluster_id: mode_name}`` dict suitable for brain_controller's
        ``cluster_labels`` plan field.

        When a cluster id appears in several modes — which the subsumption lattice
        guarantees, since a junction's id is listed under ``junction`` AND under
        ``path`` — the **most specific** mode wins: the one with the fewest ids.

        Taking the first-encountered mode (YAML order) is wrong: if ``path`` is listed
        before ``junction``, every junction id is labelled ``path``. Nothing crashes —
        but a consumer asking "which neighbour is a junction?" finds none, and the
        vehicle has nowhere to go.

        Fewest-ids is the right tie-break because the exporter builds each mode's list as
        its OWN ids plus everything that reaches it by subsumption, so a coarse mode is
        always a strict superset of the fine ones under it.
        """
        out: dict[int, str] = {}
        # ascending by set size, then by name so equal-sized sets stay deterministic
        for mode, ids in sorted(self.modes.items(), key=lambda kv: (len(kv[1]), kv[0])):
            for cid in ids:
                out.setdefault(cid, mode)
        return out


