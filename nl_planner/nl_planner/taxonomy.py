def validate_plan_modes(plan, taxonomy: ClusterTaxonomy) -> list[str]:
    """Return a list of every mode the plan names that is not in the taxonomy.

    Walks the full branch tree. Empty list = all good. ``plan`` may be a
    ``NavPlan`` instance or a dict matching that schema.

    FOUR fields name a mode, not two. ``start_mode`` / ``goal_mode`` were the
    original pair; ``hold_mode`` (the mode a dwell step must stay in) and the
    plan-level ``forbid_modes`` (the modes it must never enter) name modes just
    as literally, and both get resolved to cluster id sets downstream by
    ``branch_materializer``; ``require_modes`` likewise. All must be checked, and
    checked the same way formulas are (see ``validate_stl_modes``): otherwise a
    plan naming a nonexistent mode is rejected while a formula naming the same
    mode is accepted, which makes plan-vs-formula comparisons asymmetric.

    Checking them here rather than letting the materializer's
    ``accept_clusters()`` raise is the difference between a retryable failure and
    a crash: this list is what ``pipeline`` feeds back to the generator so it can
    fix the spelling, while a ``TaxonomyError`` out of materialization aborts the
    run. A misspelled ``forbid_modes`` entry is the worse of the two silently —
    an unresolvable negative constraint that is never enforced is indistinguish-
    able from no constraint at all.
    """
    seen: set[str] = set()
    missing: list[str] = []

    def _check(mode):
        if mode is None or mode in seen:
            return
        seen.add(mode)
        if mode not in taxonomy:
            missing.append(mode)

    def _walk(steps: Iterable):
        for step in steps:
            _check(_attr(step, "start_mode"))
            _check(_attr(step, "goal_mode"))
            _check(_attr(step, "hold_mode"))
            branches = _attr(step, "branches")
            if branches:
                for branch in branches:
                    _walk(_attr(branch, "sub_plan"))

    _walk(_attr(plan, "steps"))
    for field in ("forbid_modes", "require_modes"):
        for mode in (_attr(plan, field) or ()):
            _check(mode)
    return missing


#: Modes you travel ALONG rather than pass THROUGH. A step may legally begin and
#: end in one of these — "follow the road and stop at the 2nd bench" never changes
#: mode, and generator.md teaches exactly that shape. Everything NOT listed here is
#: treated as a point you pass through, where X -> X means you never left.
#:
#: Every vocabulary we ship, so one rule serves the pedestrian rig and CARLA.
#: Matching is on the COLLAPSED form (see ``is_extent_mode``), so a spelling only
#: needs to appear here once: `path` covers `Path`, `open_space` covers
#: `Open Space`. The reordered campus spellings (`Space: Open`, `Edge: Along`) do
#: NOT collapse onto their siblings and are listed in their own right.
EXTENT_MODES: frozenset[str] = frozenset({
    "path", "along_edge", "passage", "open_space", "other",
    "Road: On", "Along Wall", "Passage", "Open Space",
    # cluster_map.combined.yaml / cluster_map.meadow_1hz.yaml
    "Corridor", "Covered", "Edge: Along", "Space: Open",
})


def is_extent_mode(mode: str | None) -> bool:
    """True for a mode you travel ALONG rather than pass THROUGH.

    Public because ``stl_syntax`` Rule 3b needs the same distinction: you are
    always inside an extent mode, so ``Detect(<extent mode>)`` can never mark a
    transition, while ``Detect(Junction)`` names a discrete place you approach
    and the cue oracle answers it.

    Compared on the collapsed form (alphanumerics, lower-cased): ``EXTENT_MODES``
    holds ``path`` but ``cluster_map.combined.yaml`` declares ``Path``, and an
    exact-string comparison would let ``Detect(Path)`` — the leak Rule 3b exists
    to catch — through on the campus taxonomy.
    """
    if not mode:
        return False
    if mode in EXTENT_MODES or _collapse_mode(mode) in _EXTENT_COLLAPSED:
        return True
    # Car-vocabulary phase modes ("Bridge: On", "Building: Past") name a stretch you
    # are on, not a point, so dwelling in one across a step is meaningful too.
    return mode.split(":")[0].strip() in {"Bridge", "Building"}


def _collapse_mode(mode: str) -> str:
    return re.sub(r"[^A-Za-z0-9]+", "", mode).lower()


_EXTENT_COLLAPSED: frozenset[str] = frozenset(
    _collapse_mode(m) for m in EXTENT_MODES
)


#: Kept for callers that used the private spelling.
_is_extent_mode = is_extent_mode


def validate_plan_transitions(plan) -> list[str]:
    """Return every step whose mode transition cannot happen in one step.

    Two rules, both about the plan being TOPOLOGICALLY runnable rather than merely
    well-typed. ``validate_plan_modes`` checks each mode EXISTS; nothing checked
    that consecutive modes could follow one another, and a plan can satisfy every
    other validator and still describe a route no map affords.

    1. **A step must move — for POINT modes only.** ``X -> X`` is illegal when X is
       something you pass THROUGH (a junction) and legal when X is something you
       travel ALONG (a path, a wall, a passage, an open space).

       This distinction is load-bearing. Banning every ``X -> X`` also bans
       ``path -> path`` with ``cue_ordinal``, which is the encoding ``generator.md``
       Examples 4 and 5 explicitly teach for "stop at the 2nd bench": the robot is on
       the road before the bench and on the road after it, so there is no mode change
       and emitting one would stall the plan. An over-strict rule would also force
       ``path -> junction`` and so hide routing gaps in ``StepTargeter`` behind a
       rejected-but-correct plan.

    2. **Consecutive steps must chain.** Step N's ``goal_mode`` is where the robot
       is when step N+1 begins, so step N+1's ``start_mode`` must equal it.

    Rule 1 is what catches the `junction -> junction` failure. ``generator.md``
    forbids it in bold — a traversal must RETURN to `path` before the next one
    starts, because otherwise "three junctions" describes one junction you never
    leave — and the generator can emit it anyway. Such a plan passes schema
    validation, mode validation and the STL syntax check, but fails at routing
    ("no 'junction' adjacent to ...; plan and map disagree").

    Deliberately taxonomy-FREE, so it applies to any environment: it is a
    statement about the plan's own internal consistency, not about which clusters
    exist. Lives here beside ``validate_plan_modes`` so ``pipeline`` can feed both
    failures back to the generator the same way.
    """
    errs: list[str] = []

    def _walk(steps, where: str):
        nonlocal errs
        prev_goal = None
        for i, step in enumerate(steps or []):
            sm = _attr(step, "start_mode")
            gm = _attr(step, "goal_mode")
            branches = _attr(step, "branches")
            desc = (_attr(step, "description") or "")[:48]
            # A dwell step (`hold_mode` set) is `X -> X` BY CONSTRUCTION: it has
            # no destination, so there is nothing for it to end somewhere else.
            # Exempted the same way `branches` and the extent modes are — the
            # rule is "a step that claims to travel must move", and a dwell step
            # never claimed to. Without this, "hold the road until you see the
            # intersection" is rejected as "you never left the one you are in",
            # which is precisely what it is supposed to say.
            hold = _attr(step, "hold_mode")
            if sm == gm and not branches and not hold and not _is_extent_mode(sm):
                errs.append(
                    f"{where}[{i}] ({desc!r}): start_mode == goal_mode == {sm!r}. "
                    f"{sm!r} is something you pass THROUGH, so {sm!r} -> {sm!r} reads "
                    f"as never leaving the one you are already in. To traverse "
                    f"another, return to the connecting mode first: "
                    f"path -> junction, junction -> path, path -> junction. "
                    f"(Staying in the same mode IS legal for path / along_edge / "
                    f"passage / open_space — that is how 'stop at the 2nd bench' "
                    f"is written.)"
                )
            if prev_goal is not None and sm != prev_goal:
                errs.append(
                    f"{where}[{i}] ({desc!r}): start_mode {sm!r} does not continue "
                    f"from the previous step's goal_mode {prev_goal!r}. Steps run "
                    f"back to back, so step N+1 starts where step N ended."
                )
            prev_goal = gm
            if branches:
                for b_i, b in enumerate(branches):
                    sub = _attr(b, "sub_plan")
                    cue = _attr(b, "vlm_cue")
                    _walk(sub, f"{where}[{i}].branches[{b_i}] ({cue!r})")

    _walk(_attr(plan, "steps"), "steps")
    return errs


#: Nouns that name a PLACE the robot enters, not an object it sights. Arrival at one of
#: these is a cluster transition, so it belongs to the topology channel and not to the
#: visual one.
_PLACE_NOUNS = ("intersection", "junction", "crossroad", "crossroads", "four-way",
                "fourway", "roundabout", "corner")


def repair_place_detect_to_traverse(plan) -> list[str]:
    """Turn ``Detect(<place>)`` on a place-mode step into a cluster traversal. What it did.

    WHY. The system has two perception channels and they do different jobs:

      * the CLUSTER channel (LiDAR region classifier) reports which region the robot is
        in. It drives step advancement and gives the MPC its target. Progress is measured
        here.
      * the VISUAL channel (`Detect(...)`, answered by the VLM or the ground-truth oracle)
        answers DECISIONS. It picks a branch; it does not measure progress.

    "Approach the first crossroads" names a place, so arrival is a cluster transition --
    `goal_mode: junction` with `trigger: traverse`. The prompt says to use `landmark`
    "whenever the English names a thing to see", which mis-files every place noun into the
    visual channel, and the step then waits for a SIGHTING of something the region
    classifier already knows the robot is standing in.

    Example: ``transition_cue: Detect(Crossroads)`` on step 0 means brain never advances
    past step 0, even when every cue answer is correct.

    DETERMINISTIC AND SOUND: the step keeps its `goal_mode`, so where it ends is unchanged;
    only the evidence changes, from a sighting nothing publishes to the cluster arrival the
    classifier already reports. Branch `vlm_cue`s are untouched -- those ARE decisions, and
    naming a place inside one is legitimate (see the conjunctive matcher).
    """
    fixed: list[str] = []

    def walk(steps, where=""):
        for st in steps or []:
            if not isinstance(st, dict):
                continue
            cue = str(st.get("transition_cue") or "")
            m = re.match(r"\s*detect\(([^)]*)\)", cue, re.I)
            goal = str(st.get("goal_mode") or "").lower()
            if m and any(n in m.group(1).lower() for n in _PLACE_NOUNS) \
                    and any(n in goal for n in _PLACE_NOUNS):
                st["transition_cue"] = None
                st["trigger"] = "traverse"
                fixed.append(f"{where}step {st.get('step')}: {cue!r} on a {goal!r} step "
                             f"-> trigger 'traverse' (arrival is a cluster transition, "
                             f"not a sighting)")
            for i, b in enumerate(st.get("branches") or []):
                if isinstance(b, dict):
                    walk(b.get("sub_plan") or [], f"{where}br{i}/")

    if isinstance(plan, dict):
        walk(plan.get("steps") or [])
    return fixed


#: Modes you are INSIDE for the whole step, as token sets. `Detect(Path)` asks a question
#: whose answer is always yes, so the step can never advance (a deadlock).
#: `junction` is deliberately absent: you APPROACH a
#: junction, so `Detect(Junction)` is legitimate and `repair_place_detect_to_traverse`
#: owns that case.
_MEDIUM_MODES = (frozenset({"path"}), frozenset({"passage"}), frozenset({"road"}),
                 frozenset({"open", "space"}), frozenset({"edge", "along"}),
                 frozenset({"wall", "along"}))

_TURN_CUE = re.compile(r"\s*detect\(\s*(left|right|straight)\s*turn\s*\)\s*$", re.I)


def _mode_tokens(name) -> frozenset:
    """`"Edge: Along"`, `"AlongEdge"` and `"along_edge"` all -> {along, edge}."""
    s = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", " ", str(name or ""))
    return frozenset(w for w in re.split(r"[^A-Za-z0-9]+", s.lower()) if w)


def repair_medium_detect_cue(plan) -> list[str]:
    """Fix a `transition_cue` that asks to SEE the medium, or to see a turn. What it did.

    Two shapes are repaired. They are the unanswerable cues caused by the prompt's own
    encoding; most other unanswerable cues name referents this deployment has no family
    for at all, which are not repairable here and are left for the gate to report.

      1. `Detect(<medium>)` ENTERING that medium -- `Detect(Path)` on an `Other -> Path`
         step, `Detect(Passage)` on a `Path -> Passage` step. The evidence
         it wants is a cluster arrival the region classifier already publishes, so this
         becomes `trigger: traverse` with no cue. Exactly the argument
         `repair_place_detect_to_traverse` makes for place nouns, and sound for the same
         reason: `goal_mode` is untouched, so WHERE the step ends does not change -- only
         what counts as having got there.

      2. `Detect(RightTurn)` -- a MANOEUVRE written as an object, typically on a step
         whose `start_mode` equals its `goal_mode` (`Path -> Path`,
         `Edge: Along -> Edge: Along`). Becomes `Bearing(Right) completed` with
         `trigger: topology`, which is what the prompt's own verb table prescribes and
         what example 1 of `generator_v5.md` already demonstrates. `Bearing(...)` is
         resolved from the trajectory, so `cue_vocab._TRAJECTORY_CUE` exempts it and it is
         answerable by construction.

    WHY RULE 1 REQUIRES `start_mode != goal_mode` AND A NAME MATCH. Turning a cue into
    `traverse` is only sound when a cluster transition actually happens. On a `Path ->
    Path` step there is none, so `traverse` would either complete instantly or never --
    a semantics change, not a repair. A `Detect(Passage)` on a `Path -> Path` step is
    left alone for precisely this reason; the gate reports it and the model retries.

    BRANCH STEPS ARE SKIPPED. A step with `branches` asks its question through the branch
    cues (`repair_prose_decision_cue` owns that); these shapes occur on `transition_cue`.
    Scoping keeps a decision step's evidence out of this function.
    """
    fixed: list[str] = []

    def walk(steps, where=""):
        for st in steps or []:
            if not isinstance(st, dict):
                continue
            for i, b in enumerate(st.get("branches") or []):
                if isinstance(b, dict):
                    walk(b.get("sub_plan") or [], f"{where}br{i}/")
            if st.get("branches"):
                continue
            cue = str(st.get("transition_cue") or "")
            if not cue:
                continue

            turn = _TURN_CUE.match(cue)
            if turn:
                d = turn.group(1).capitalize()
                st["transition_cue"] = f"Bearing({d}) completed"
                st["trigger"] = "topology"
                fixed.append(f"{where}step {st.get('step')}: {cue!r} is a manoeuvre, not "
                             f"an object -> 'Bearing({d}) completed' / trigger 'topology'")
                continue

            m = re.match(r"\s*detect\(([^)]*)\)\s*$", cue, re.I)
            if not m:
                continue
            named = _mode_tokens(m.group(1))
            goal = _mode_tokens(st.get("goal_mode"))
            start = _mode_tokens(st.get("start_mode"))
            if named and named in _MEDIUM_MODES and named == goal and start != goal:
                st["transition_cue"] = None
                st["trigger"] = "traverse"
                fixed.append(
                    f"{where}step {st.get('step')}: {cue!r} asks to SEE the medium it is "
                    f"entering -> trigger 'traverse' (arrival at {st.get('goal_mode')!r} "
                    f"from {st.get('start_mode')!r} is a cluster transition)")

    if isinstance(plan, dict):
        walk(plan.get("steps") or [])
    return fixed


def repair_prose_decision_cue(plan) -> list[str]:
    """Null out a prose ``transition_cue`` on a step that has branches. Returns what it did.

    DETERMINISTIC AND SOUND, and it is the fix ``validate_decision_cues`` already names in
    its own error text: "Either set transition_cue to null and let the branches decide".
    There is exactly one repair and it needs no model.

    Sound because the branches carry the perception question. A decision step's own cue is
    redundant when it is a real predicate and unanswerable when it is prose -- "decision
    point" is not something any publisher can answer, so the step never completes even when
    a branch resolves correctly, and the robot drives past its target until the cue budget
    kills the run.

    WHY IT EXISTS. On deep (depth-3) missions this is a common failure, typically with
    the literal string `"decision point"`. Re-prompting re-rolls a correct plan to delete
    one field.

    Operates on a RAW dict, before validation, beside repair_degenerate_branches.
    """
    fixed: list[str] = []

    def walk(steps, where=""):
        for st in steps or []:
            if not isinstance(st, dict):
                continue
            br = st.get("branches")
            cue = st.get("transition_cue")
            if br and cue:
                low = str(cue).lower()
                if "detect(" not in low and "bearing(" not in low:
                    st["transition_cue"] = None
                    fixed.append(f"{where}step {st.get('step')}: dropped prose cue {cue!r} "
                                 f"from a branching step")
            for i, b in enumerate(br or []):
                if isinstance(b, dict):
                    walk(b.get("sub_plan") or [], f"{where}br{i}/")

    if isinstance(plan, dict):
        walk(plan.get("steps") or [])
    return fixed


def repair_degenerate_branches(plan) -> list[str]:
    """Splice out decision steps whose ONLY branch is ``default``. Returns what it did.

    DETERMINISTIC AND SOUND, because a decision step with one branch is not a decision.
    The schema already refuses it (``branches must have >= 2 entries``); this removes the
    wrapper and puts the branch's own steps in its place, which is what the step meant.

    WHY IT EXISTS. On deep (depth-3) missions the model tends to fail this rule at a
    consistent structural position, while NOT getting the deep decision wrong -- the real
    third-level decision underneath is correctly formed with its cue branch and default:

        sub[2].br[0].sub[0]  decision: 1 branch ['default']      <- null wrapper
            sub[0] plain: Approach the third junction
            sub[1] decision: 2 branches ['cone present', 'default']   <- correct

    It wraps the *continuation* of a branch in a pointless default-only decision. The plan
    is right and the shape is wrong, so re-prompting re-rolls a correct plan to fix a
    structural tic. This edits the shape and leaves the content untouched -- the same
    argument that justifies ``repair_cue_ordinal``.

    Operates on a RAW dict, before validation, because this failure kills the model_validate
    call that ``repair_cue_ordinal`` runs after.
    """
    fixed: list[str] = []

    def only_default(step) -> bool:
        br = step.get("branches")
        if not isinstance(br, list) or len(br) != 1:
            return False
        cue = (br[0].get("vlm_cue") or "").strip().lower()
        return cue == "default"

    def splice(steps, where=""):
        if not isinstance(steps, list):
            return steps
        out = []
        for st in steps:
            if not isinstance(st, dict):
                out.append(st)
                continue
            if only_default(st):
                inner = splice(st["branches"][0].get("sub_plan") or [], where)
                fixed.append(f"{where}step {st.get('step')}: default-only decision spliced "
                             f"({len(inner)} step(s) lifted)")
                out.extend(inner)
                continue
            if isinstance(st.get("branches"), list):
                for i, b in enumerate(st["branches"]):
                    if isinstance(b, dict):
                        b["sub_plan"] = splice(b.get("sub_plan") or [],
                                               f"{where}br{i}/")
            out.append(st)
        # step indices are 0-based WITHIN their list, so renumber after any splice
        for i, st in enumerate(out):
            if isinstance(st, dict) and "step" in st:
                st["step"] = i
        return out

    if isinstance(plan, dict):
        plan["steps"] = splice(plan.get("steps") or [])
    return fixed


def repair_cue_ordinal(plan) -> list[str]:
    """Strip the redundant ``cue_ordinal`` from double-counted steps. Returns what it did.

    DETERMINISTIC, and sound for the reason ``validate_cue_ordinal`` gives: when a plan
    already contains two or more steps ending in the same POINT mode, the count lives in
    the step index and a ``cue_ordinal`` on any of them "is redundant". Redundant is not
    ambiguous -- there is exactly one repair, and it needs no model.

    Worth doing rather than re-prompting: this validator is a leading cause of
    non-convergence. A retry re-rolls the whole plan and may lose parts that were already
    right; this edits one field and leaves everything else untouched.

    Landmark counting is untouched, exactly as in the validator -- a landmark plan has one
    such step, not several.
    """
    fixed: list[str] = []

    def walk(steps, where=""):
        by_mode: dict[str, list] = {}
        for st in steps or []:
            if not isinstance(st, dict):
                continue
            gm = st.get("goal_mode")
            if gm and not is_extent_mode(gm):
                by_mode.setdefault(gm, []).append(st)
        for mode, group in by_mode.items():
            if len(group) < 2:
                continue                      # one step: a landmark count, leave it
            for st in group:
                if st.get("cue_ordinal"):
                    fixed.append(
                        f"{where}steps[{st.get('step')}]: dropped cue_ordinal="
                        f"{st['cue_ordinal']} -- {mode!r} is unrolled across "
                        f"{len(group)} steps, so the index already carries the count")
                    st["cue_ordinal"] = None
        for i, st in enumerate(steps or []):
            for b in ((st or {}).get("branches") or []):
                walk(b.get("sub_plan"), f"{where}steps[{i}].branch.")

    walk(plan.get("steps") if isinstance(plan, dict) else
         getattr(plan, "steps", None) and
         __import__("json").loads(plan.model_dump_json())["steps"])
    return fixed


def validate_cue_ordinal(plan) -> list[str]:
    """Return every step that DOUBLE-COUNTS an unrolled traversal.

    Fourth site of the same disease as ``validate_decision_cues``: the prompt states a
    rule, nothing enforces it, and the model breaks it. ``generator.md`` is explicit --

        Counting TRAVERSALS (intersections) -> UNROLL. Every unrolled step must have
        cue_ordinal: null; the step index already encodes "second". Setting
        cue_ordinal on an unrolled step DOUBLE-COUNTS: the robot would sit in that
        step waiting to see two MORE intersections.

        Counting LANDMARK SIGHTINGS (benches, doors) -> ONE step, cue_ordinal: N.

    The model frequently unrolls correctly AND stamps ``cue_ordinal`` anyway on
    intersection-counting plans. The error is silent -- the plan passes modes,
    transitions and cues, and would drive to the 5th intersection when asked for the 3rd.

    **The rule, and why it is decidable.** A point mode (``junction``) is something you
    pass THROUGH, so N of them means N steps. An extent mode (``path``) is something you
    travel ALONG, so "the 2nd bench" is one ``path -> path`` step carrying
    ``cue_ordinal: 2``. The two encodings are therefore distinguishable without knowing
    what is being counted: if a plan already contains two or more steps ending in the
    same point mode, the count is in the step INDEX, and a ``cue_ordinal`` on any of
    them is redundant. Landmark counting is untouched, because a landmark plan has one
    such step, not several.

    Taxonomy-free like its neighbours -- a statement about the plan's own consistency.
    """
    errs: list[str] = []
    unrolled: dict[str, int] = {}
    carriers: list[tuple[str, int, str, int]] = []

    def _walk(steps, where: str):
        for i, step in enumerate(steps or []):
            gm = _attr(step, "goal_mode")
            ordinal = _attr(step, "cue_ordinal")
            if gm and not is_extent_mode(gm):
                unrolled[gm] = unrolled.get(gm, 0) + 1
                if ordinal:
                    carriers.append((where, i, gm, int(ordinal)))
            for br in (_attr(step, "branches") or ()):
                _walk(_attr(br, "sub_plan"), f"{where}[{i}].branch")

    _walk(_attr(plan, "steps"), "steps")
    for where, i, gm, ordinal in carriers:
        if unrolled.get(gm, 0) >= 2:
            errs.append(
                f"{where}[{i}]: goal_mode {gm!r} appears in {unrolled[gm]} steps AND this "
                f"step sets cue_ordinal={ordinal}. That double-counts -- the step index "
                f"already encodes the ordinal, so the robot would wait for {ordinal} MORE "
                f"{gm}s. Unroll OR use cue_ordinal, never both (generator.md: 'NEVER do "
                f"both for the same count')."
            )
    return errs


def validate_decision_cues(plan) -> list[str]:
    """Return every branching step that also carries a predicate-free landmark cue.

    Third site of one disease: **an unanswerable cue on a step that gates
    advancement.** Rule 3b in ``stl_syntax`` closed the first (a mode name inside
    ``Detect(...)``). This is the second, and it evades 3b because it is not in the
    STL at all — it is the ``transition_cue`` JSON field. Example::

        step 2: path -> junction  trigger=landmark  transition_cue='decision point'
                branch 'cone is present in the junction' -> Bearing(Straight)
                branch 'default'                         -> Bearing(Right)

    The branches already carry the perception question; the step's own cue is prose
    describing what the step IS. The branch resolves correctly and drives to the right
    exit — and then the step never completes, so the vehicle keeps driving until the
    cue budget ends the run.

    **Why the rule is structural rather than a check on the cue text.**
    ``transition_cue`` is free text BY DESIGN (``schemas.PlanStep``: brain's VLM polls
    it) and ``schemas.infer_trigger`` deliberately maps free text to ``landmark``. So
    "is this cue answerable" is not decidable — ``"a light brown bench"`` is a
    legitimate pedestrian cue and ``"decision point"`` is not, and nothing in the
    string tells them apart. What IS decidable is the redundancy: a step whose
    branches ask the question does not need to ask it again, and if it does ask, the
    ask must be a predicate something can answer.

    Scoped to branching steps on purpose. A predicate-free cue on a plain step is the
    documented pedestrian shape and is left alone.

    Taxonomy-free, like ``validate_plan_transitions`` — a statement about the plan's
    own consistency, so it serves any environment.
    """
    errs: list[str] = []

    def _walk(steps, where: str):
        for i, step in enumerate(steps or []):
            branches = _attr(step, "branches")
            cue = (_attr(step, "transition_cue") or "").strip()
            if branches and cue:
                low = cue.lower()
                # `Bearing(Right) completed` counts as a predicate — the trailing
                # prose is harmless and the maneuver extraction reads it by substring.
                if "detect(" not in low and "bearing(" not in low:
                    desc = (_attr(step, "description") or "")[:48]
                    cues = [(_attr(b, "vlm_cue") or "") for b in branches]
                    errs.append(
                        f"{where}[{i}] ({desc!r}): transition_cue {cue!r} is prose, not "
                        f"a Detect(...) / Bearing(...) predicate, on a step that also "
                        f"has branches {cues}. Nothing can answer it, so the step never "
                        f"completes even when a branch resolves correctly — the robot "
                        f"drives past its target until the cue budget kills the run. "
                        f"The branches already carry the perception question. Either "
                        f"set transition_cue to null and let the branches decide, or "
                        f"make it a real predicate for the thing that marks arrival "
                        f"(e.g. Detect(Intersection)). Do not describe the step."
                    )
            if branches:
                for b_i, b in enumerate(branches):
                    _walk(_attr(b, "sub_plan"),
                          f"{where}[{i}].branches[{b_i}] ({_attr(b, 'vlm_cue')!r})")

    _walk(_attr(plan, "steps"), "steps")
    return errs


def _attr(obj, name: str):
    if isinstance(obj, dict):
        return obj.get(name)
    return getattr(obj, name, None)


