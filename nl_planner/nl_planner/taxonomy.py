def load_taxonomy(path: str | Path) -> ClusterTaxonomy:
    """Read and validate ``path`` (a YAML file). Raises ``TaxonomyError``."""
    p = Path(path)
    if not p.exists():
        raise TaxonomyError(f"taxonomy file not found: {p}")
    try:
        raw = yaml.safe_load(p.read_text()) or {}
    except yaml.YAMLError as exc:
        raise TaxonomyError(f"could not parse YAML at {p}: {exc}") from exc
    if not isinstance(raw, dict):
        raise TaxonomyError(f"taxonomy at {p} must be a mapping at the top level")

    env = raw.get("environment")
    if not isinstance(env, str) or not env.strip():
        raise TaxonomyError(f"taxonomy at {p} is missing a non-empty 'environment' string")

    modes_raw = raw.get("modes") or {}
    if not isinstance(modes_raw, dict) or not modes_raw:
        raise TaxonomyError(f"taxonomy at {p} must declare a non-empty 'modes' mapping")

    modes: dict[str, tuple[int, ...]] = {}
    for mode, ids in modes_raw.items():
        if not isinstance(mode, str) or not mode.strip():
            raise TaxonomyError(f"mode keys must be non-empty strings; got {mode!r}")
        if not isinstance(ids, list) or not ids:
            raise TaxonomyError(
                f"mode {mode!r} must map to a non-empty list of cluster ids"
            )
        ints: list[int] = []
        for x in ids:
            if not isinstance(x, int):
                raise TaxonomyError(
                    f"cluster ids under mode {mode!r} must be ints; got {x!r}"
                )
            ints.append(x)
        modes[mode] = tuple(ints)

    # Optional: which AXIS each mode measures. Modes on the SAME axis are alternatives
    # (union); modes on DIFFERENT axes are simultaneous facts about one place, and must
    # both hold (intersection).
    #
    # This exists because a sidewalk is not a third kind of route -- topologically it IS a
    # path. What distinguishes it is the SURFACE. Modelling it as a separate topology mode
    # made `require_modes: [sidewalk]` and a formula's `G Phi_Path` merge by union into
    # "sidewalk OR road", which is satisfied by driving the whole route on the
    # carriageway -- the mission's exact opposite. On separate axes they intersect to
    # "a path whose surface is sidewalk", which is what the English said.
    axes = raw.get("axes") or {}
    source = raw.get("source")

    # Optional per-mode execution metadata (see ClusterTaxonomy.mode_meta).
    mode_meta_raw = raw.get("mode_meta") or {}
    if not isinstance(mode_meta_raw, dict):
        raise TaxonomyError(f"'mode_meta' in {p} must be a mapping if present")
    mode_meta: dict[str, dict[str, object]] = {}
    for mode, meta in mode_meta_raw.items():
        if mode not in modes:
            raise TaxonomyError(
                f"mode_meta references unknown mode {mode!r} in {p}; "
                f"legal modes: {sorted(modes)}"
            )
        if not isinstance(meta, dict):
            raise TaxonomyError(f"mode_meta[{mode!r}] in {p} must be a mapping")
        entry: dict[str, object] = {}
        if "perception_backed" in meta:
            entry["perception_backed"] = bool(meta["perception_backed"])
        if meta.get("accept_degraded") is not None:
            deg = meta["accept_degraded"]
            if not isinstance(deg, list):
                raise TaxonomyError(
                    f"mode_meta[{mode!r}].accept_degraded in {p} must be a list of ints"
                )
            ids: list[int] = []
            for x in deg:
                if not isinstance(x, int):
                    raise TaxonomyError(
                        f"mode_meta[{mode!r}].accept_degraded must contain ints; got {x!r}"
                    )
                ids.append(x)
            entry["accept_degraded"] = tuple(ids)
        # Free-form predicate hooks used when perception_backed is False.
        for key in ("enter_on", "exit_on", "requires_sensor"):
            if meta.get(key) is not None:
                entry[key] = str(meta[key])
        mode_meta[mode] = entry

    # Optional CARLA spatial data: centroids + bearing_map
    centroids_raw = raw.get("centroids") or {}
    centroids: dict[str, tuple[float, float, float]] = {}
    for k, v in centroids_raw.items():
        if isinstance(v, (list, tuple)) and len(v) >= 2:
            centroids[str(k)] = (float(v[0]), float(v[1]), float(v[2]) if len(v) > 2 else 0.0)

    bearing_map_raw = raw.get("bearing_map") or {}
    bearing_map: dict[str, float] = {str(k): float(v) for k, v in bearing_map_raw.items()}

    return ClusterTaxonomy(
        axes=axes,
        environment=env,
        source=source if isinstance(source, str) else None,
        modes=modes,
        mode_meta=mode_meta or None,
        centroids=centroids or None,
        bearing_map=bearing_map or None,
    )


